#!/bin/bash

# Путь к папке, где находятся скрипты проекта
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# Путь к основному скрипту, который мы будем тестировать
ARCHIVER="$SCRIPT_DIR/archive_logs.sh"

# Временная папка для всех тестов
TEST_ROOT="$(mktemp -d)"

# Удаляем временную папку после завершения тестов
trap 'rm -rf "$TEST_ROOT"' EXIT

# Счётчики результатов
PASSED=0
FAILED=0


# --------------------------------------------------
# Вспомогательные функции
# --------------------------------------------------

pass_test() {
    echo "PASS: $1"
    PASSED=$((PASSED + 1))
}

fail_test() {
    echo "FAIL: $1"
    FAILED=$((FAILED + 1))
}


# Создание тестовой папки
create_test_environment() {
    LOG_DIR="$TEST_ROOT/log"
    BACKUP_DIR="$TEST_ROOT/backup"

    mkdir -p "$LOG_DIR"
    mkdir -p "$BACKUP_DIR"
}


# --------------------------------------------------
# Проверка основного скрипта
# --------------------------------------------------

if [ ! -f "$ARCHIVER" ]; then
    echo "Ошибка: не найден $ARCHIVER"
    echo "Сначала должен появиться файл archive_logs.sh"
    exit 1
fi


echo "========================================"
echo "Тестирование archive_logs.sh"
echo "========================================"
echo


# --------------------------------------------------
# Здесь ниже будут сами тесты
# --------------------------------------------------

echo "Тесты пока не добавлены."
echo "Каркас test_archive.sh готов."


# --------------------------------------------------
# Итог
# --------------------------------------------------

echo
echo "========================================"
echo "Результат"
echo "========================================"
echo "Пройдено: $PASSED"
echo "Провалено: $FAILED"
